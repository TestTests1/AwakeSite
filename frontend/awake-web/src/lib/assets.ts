/**
 * Откуда берутся модели фигур и заграждений.
 *
 * По умолчанию — из самой раздачи сайта, то есть из папки `public`. Так работает
 * стенд, и так же соберётся сайт, если модели лежат в репозитории.
 *
 * Если моделей в репозитории нет — а это разумно, они вынуты из игровых
 * ассетов, — задайте при сборке `VITE_ASSETS_URL` с адресом хранилища, куда они
 * выложены рядом с картами локаций. Переменная времени сборки: Vite
 * подставляет её в бандл, после сборки поменять нельзя.
 */
const BASE = (import.meta.env.VITE_ASSETS_URL ?? '').replace(/\/$/, '')

export function assetUrl(path: string): string {
  return `${BASE}${path}`
}

import * as THREE from 'three'

/**
 * Фильтрация текстур карты.
 *
 * Экспортёр помечает все текстуры фильтром NEAREST без мипмап — так блоки
 * выглядят в игре: резкими, без размытия. Вблизи это верно, но вдаль
 * разваливается. На пиксель экрана приходится десяток текселей, NEAREST берёт
 * из них один, и от малейшего сдвига камеры выбор меняется — поверхность
 * переливается крупой. При заходе на карту видно всю локацию разом с полутора
 * тысяч блоков, каждая грань мельче пикселя, и шум там максимальный.
 *
 * Лечится мипмапами: уменьшенные копии текстуры считаются заранее, и вдаль
 * берётся та, где тексель примерно равен пикселю. Выбирать больше не из чего —
 * рябить нечему.
 *
 * Фильтр уменьшения именно NearestMipmapLinear, а не Linear-версия: увеличение
 * (magFilter) не трогаем вовсе, поэтому вблизи блоки остаются такими же
 * ступенчатыми, как были, — вид игры не меняется. Различаются только дальние
 * поверхности. «Linear» в названии относится к переходу между двумя соседними
 * уровнями: без смешивания была бы видна граница, где уровень сменился.
 *
 * Анизотропия добивает то, что мипмапам не под силу. У земли, уходящей к
 * горизонту, тексель растянут вдоль взгляда сильнее, чем поперёк, и один общий
 * уровень либо мылит, либо рябит. Шестнадцать — это запрос: three.js сам
 * урежет его до предела видеокарты, так что значение безопасно на любой.
 *
 * Цена — треть текстурной памяти сверху (замер: «Низина» 76 → 101 МБ,
 * «Хвойный» 103 → 137 МБ). Карта в сцене одна, это приемлемо.
 */
const ANISOTROPY = 16

/**
 * Порог прозрачности для материалов с прорезями.
 *
 * У травы, листвы и решёток прозрачность решается порогом: тексель либо
 * рисуется, либо нет. Мипмапа усредняет альфу вместе с цветом, и на дальних
 * уровнях та проседает — при штатном пороге 0.5 трава начала бы редеть, а
 * потом пропадать вовсе. Порог поэтому опускается: прорези остаются на месте,
 * их края вдали чуть полнеют. Это меньшее зло, чем исчезающая листва.
 *
 * Исключать такие материалы из мипмап целиком было бы хуже всего: экспортёр
 * гонит через маску и обычные сплошные блоки — шифер, доски, CTM-переходы, — а
 * это 61 % геометрии «Низины» и 39 % «Хвойного». Настоящих прорезей среди них
 * меньше десятой доли процента, и у сплошных блоков альфа всюду единица, так
 * что порог для них не значит ничего.
 */
const CUTOUT_ALPHA_TEST = 0.2

/** Текстуры общие между материалами, поэтому каждую правим один раз. */
export function improveTextureFiltering(scene: THREE.Object3D): void {
  const done = new Set<THREE.Texture>()

  scene.traverse((object) => {
    if (!(object instanceof THREE.Mesh) || !object.material) return

    const materials = Array.isArray(object.material) ? object.material : [object.material]
    for (const material of materials) {
      if (material.alphaTest > CUTOUT_ALPHA_TEST) {
        material.alphaTest = CUTOUT_ALPHA_TEST
        material.needsUpdate = true
      }

      const map = (material as THREE.MeshStandardMaterial).map
      if (!map || done.has(map)) continue
      done.add(map)

      map.generateMipmaps = true
      map.minFilter = THREE.NearestMipmapLinearFilter
      map.anisotropy = ANISOTROPY
      map.needsUpdate = true
    }
  })
}
